/**
 * 操作ルート
 *
 * @param   wk
 *
 * @retval  BOOL    終わったらTRUE
 */
//----------------------------------------------------------------------------------
static BOOL MainCtrl( DEBUG_INPUT_WORK* wk )
{
  if( PRINT_UTIL_Trans(&wk->PrintUtil, wk->PrintQue) )
  {
    const STR_PARAM_DISPLAY *cp_display = Page_GetStrParamDisplay( wk->p_pageData );

    switch( wk->Seq ){
    case SEQ_DRAW_CAPTION:
      {
        int i;
        for(i=0; i<cp_display->len; ++i){
          PrintCaption( wk, &cp_display->strParams[i] );
        }
      }
      wk->Seq = SEQ_DRAW_BOX;
      break;      
    case SEQ_DRAW_BOX:
      {
        int i;
        for(i=0; i<cp_display->len; ++i){
          if( cp_display->strParams[i].Type == STR_TYPE_EDITSTR )
          {
            UpdateStrBox( wk, cp_display->strParams[i].editBoxID);
          }
          else
          {
            UpdateBox( wk, cp_display->strParams[i].editBoxID, wk->BoxValue[ cp_display->strParams[i].editBoxID ] );
          }
        }
        wk->Seq = SEQ_WAIT_CTRL;
      }
      break;      
    case SEQ_WAIT_CTRL:
      //ページ更新
      {
        BOOL is_update  = FALSE;
        if( GFL_UI_KEY_GetTrg() == PAD_BUTTON_L )
        {
          Page_PrevPage( wk->p_pageData );
          is_update = TRUE;
        }
        if( GFL_UI_KEY_GetTrg() == PAD_BUTTON_R )
        {
          Page_NextPage( wk->p_pageData );
          is_update = TRUE;
        }
        if( is_update )
        {
          wk->Seq = SEQ_REDRAW;
          break;
        }
      }
      //キー操作
      {
        u16 key = GFL_UI_KEY_GetTrg();
        if( key & PAD_BUTTON_A )
        {
          Page_ReStoreData( wk->p_resort_sv, wk );
          key |= PAD_BUTTON_B;
          break;
        }

        if( key & PAD_BUTTON_B )
        {
          wk->p_pageData = Page_PopPage( wk->p_pageData );
          if( wk->p_pageData == NULL )
          {
            //アプリ終了
            return TRUE;
          }
          else
          {
            wk->Seq = SEQ_REDRAW;
            break;
          }
        }
      }

      //ボックスタッチ待ち
      wk->BoxIdx = CheckBoxTouch( wk );
      if( wk->BoxIdx >= 0 )
      {
        const STR_PARAM* p  = NULL;

        p = GetBoxForEditBoxID( wk, wk->BoxIdx );
        
        if( p == NULL ) break;

        switch( p->Type ){
        case STR_TYPE_STR:
        case STR_TYPE_EDITSTR:  
          {            
            static const GFL_SKB_SETUP setup = {
              STRBUF_LEN, GFL_SKB_STRTYPE_STRBUF,
              GFL_SKB_MODE_KATAKANA, TRUE, 0, PAD_BUTTON_START,
              PRINT_FRAME, SKB_PALIDX1, SKB_PALIDX2,
            };
            wk->skbSetup = setup;
            GetBoxStr( wk, wk->BoxIdx, wk->StrBuf );
            if( is_hiragana(wk->StrBuf) ){
              wk->skbSetup.mode = GFL_SKB_MODE_HIRAGANA;
            }
            wk->skb = GFL_SKB_Create( (void*)(wk->StrBuf), &wk->skbSetup, wk->HeapID );
            COMPSKB_Setup( &wk->comp, wk->skb, wk->StrBuf, p->arg, wk->HeapID );
            wk->Seq = SEQ_INPUT_STR;            
          }
          break;
        case STR_TYPE_NUM:
          NumInput_Setup( &wk->NumInput, wk->StrBuf, wk->Win, wk->Font,
              &wk->PrintUtil, wk->PrintQue, p, wk->BoxValue[wk->BoxIdx], 0,wk, NUMINPUT_TYPE_DECIMAL );
          wk->Seq = SEQ_INPUT_NUM;
          break;          
        case STR_TYPE_BIT:
          NumInput_Setup( &wk->NumInput, wk->StrBuf, wk->Win, wk->Font,
              &wk->PrintUtil, wk->PrintQue, p, wk->BoxValue[wk->BoxIdx], p->arg, wk, NUMINPUT_TYPE_BIT );
          wk->Seq = SEQ_INPUT_NUM;
          break;
        case STR_TYPE_SWITCH:
          {
            u32 val = wk->BoxValue[wk->BoxIdx];

            if( wk->touch_prev_flag ){
              if( val == 0 ){
                val = p->arg2-1;
              }
              else
              {
                --val;
              }
            }else{
              if( ++val >= p->arg2 ){
                val = 0;
              }
            }

            UpdateBox( wk, wk->BoxIdx, val );
          }
          break;
        case STR_TYPE_BUTTON:
          {
            ButtonAction_Callback action  = (ButtonAction_Callback)p->arg2;
            if( action != NULL )
            {
              action( wk, p );
            }
          }
          break;
        }       //end switch
        break;
      }
      break;
    case SEQ_INPUT_STR:      
      if( COMPSKB_Main(&wk->comp) )
      {
        int idx;
        const STR_PARAM* p;
        p = GetBoxForEditBoxID( wk, wk->BoxIdx );
        if( p == NULL ) break;

        if ( p->Type == STR_TYPE_EDITSTR)
        {

          const u32 strBoxID  = p->editBoxID - EDITBOX_ID_MAX;
          GF_ASSERT( p->editBoxID >= EDITBOX_ID_MAX);

          if( GFL_STR_GetBufferLength(wk->StrBuf) == 0 ){
            idx = 0;
          }
          GFL_STR_CopyBuffer( wk->BoxStrBuf[ strBoxID ], wk->StrBuf );
          idx = 0;
          UpdateStrBox( wk, wk->BoxIdx);
        }
        else
        {
          idx = COMPSKB_GetWordIndex( &wk->comp );
          if( idx < 0 ){
            if( GFL_STR_GetBufferLength(wk->StrBuf) == 0 ){
              idx = 0;
            }
          }
          if( idx >= 0 ){
            UpdateBox( wk, wk->BoxIdx, idx );
          }
        }
        COMPSKB_Cleanup( &wk->comp );
        GFL_SKB_Delete( wk->skb );
        wk->Seq = SEQ_WAIT_CTRL;
      }      
      break;
    case SEQ_INPUT_NUM:
      if( NumInput_Main(&wk->NumInput) )
      {
        u32 num = NumInput_GetNum( &wk->NumInput );
        OS_TPrintf( "num_input %d\n", num );
        UpdateBox( wk, wk->BoxIdx, num );
        wk->Seq = SEQ_WAIT_CTRL;
      }
      break;

    case SEQ_REDRAW:
      wk->Seq = SEQ_DRAW_CAPTION;
      GFL_BMP_Clear( wk->Bmp, 0x0f );
      break;
    }    //end switch
  } //end if
  return FALSE;
}

