static BOOL NumInput_Main( NUMINPUT_WORK* wk )
{
  u32 x,y;
  u16 key = GFL_UI_KEY_GetTrg();

  if( (key & PAD_BUTTON_A)|| GFL_UI_TP_GetPointTrg( &x, &y ) ){
    switch( wk->type )
    {
    case NUMINPUT_TYPE_DECIMAL:
      wk->Num = CalcInputNum( wk );
      break;
    case NUMINPUT_TYPE_BIT:
      wk->Num = Calc2To10( CalcInputNum( wk ), wk->Disit );
      break;
    }
    return TRUE;
  }
  if( key & PAD_BUTTON_B ){
    return TRUE;
  }

  {
    u8 update = TRUE;
    u8 up_key_flg = FALSE;
    do {
      if( key & PAD_KEY_LEFT ){
        if( wk->CurDisit < (wk->Disit-1) ){
          wk->CurDisit++;
          break;
        }
      }
      if( key & PAD_KEY_RIGHT ){
        if( wk->CurDisit > 0 ){
          wk->CurDisit--;
          break;
        }
      } 
      if( wk->type == NUMINPUT_TYPE_DECIMAL )
      {
        if( key & PAD_KEY_UP )
        {
          int k = wk->CurDisit;
          while( k < (wk->Disit) ){
            wk->NumAry[k]++;
            if( wk->NumAry[k] <= 9 ){ break; }
            wk->NumAry[k] = 0;
            ++k;
          }
          // 桁あふれしたら最大値に
          if( k == (wk->Disit) ){
            OS_Printf("↑　ケタあふれ\n");
            SetAryNumInput( wk, wk->NumMax );
          }
          //上キー押下チェックON
          up_key_flg = TRUE;
          break;
        }
        if( key & PAD_KEY_DOWN )
        {
          int k = wk->CurDisit;
          while( k < (wk->Disit) )
          {
            wk->NumAry[k]--;
            if( wk->NumAry[k] >= 0 ){ break; }
            wk->NumAry[k] = 9;
            ++k;
          }
          // 桁あふれしたら最小値に
          if( k == (wk->Disit) ){
            OS_Printf("↓　ケタあふれ\n");
            SetAryNumInput( wk, wk->NumMin );
          }
          break;
        }
        if( key & PAD_BUTTON_L ){
          SetAryNumInput( wk, wk->NumMax );
          break;
        }
        if( key & PAD_BUTTON_R ){
          SetAryNumInput( wk, wk->NumMin );
          break;
        }
      }
      else if( wk->type == NUMINPUT_TYPE_BIT )
      {
        if( key & PAD_KEY_UP
            || key & PAD_KEY_DOWN )
        {
          int k = wk->CurDisit;
          wk->NumAry[k] ^= 1;
          //上キー押下チェックON
          break;
        }
      }
      update = FALSE;
    }while(0);

    if( update ){
      u32 num = CalcInputNum( wk );

      //数値加算したのに値が下回ったをチェック（値のオーバーフローチェック）
      if ( up_key_flg )
      {
        if (num < wk->DispNumWork)
        {
          num = wk->NumMax;
          SetAryNumInput( wk, num );
        }
      }

      if( num > wk->NumMax ){
        num = wk->NumMax;
        SetAryNumInput( wk, num );
      }
      if( num < wk->NumMin ){
        num = wk->NumMin;
        SetAryNumInput( wk, num );
      }
      DrawNumInput( wk );
      wk->DispNumWork = num;
    }
  }
  return FALSE;
}
