static const STR_PARAM_DISPLAY *Page_GetStrParamDisplay( STR_PARAM_PAGE_STACK *p_wk )
{
  return &p_wk->cp_now_page->display[ p_wk->page ];
}
static void Page_NextPage( STR_PARAM_PAGE_STACK *p_wk )
{
  p_wk->page++;
  if( p_wk->page >= p_wk->cp_now_page->len )
  {
    p_wk->page = 0;
  }
}
static void Page_PrevPage( STR_PARAM_PAGE_STACK *p_wk )
{
  p_wk->page--;

  if( p_wk->page < 0 )
  {
    p_wk->page  = p_wk->cp_now_page->len-1;
  }
}
static STR_PARAM_PAGE_STACK * Page_PushPage( STR_PARAM_PAGE_STACK *p_wk, const STR_PARAM_PAGE *cp_page )
{
  STR_PARAM_PAGE_STACK *p_stack = GFL_HEAP_AllocClearMemory( HEAPID_WIFIMATCH_DEBUG, sizeof( STR_PARAM_PAGE_STACK ) );
  p_stack->p_prev = p_wk;
  p_stack->cp_now_page = cp_page;

  return p_stack;
}
static STR_PARAM_PAGE_STACK * Page_PopPage( STR_PARAM_PAGE_STACK *p_wk )
{
  GF_ASSERT(p_wk != NULL );
  {
    STR_PARAM_PAGE_STACK *p_prev = p_wk->p_prev;
    GFL_HEAP_FreeMemory( p_wk );
    return p_prev;
  }
}
static void Page_StoreData( DEBUG_INPUT_WORK *p_wk, RESONANCE_RESORT_SV *p_resort_sv )
{
  if( p_wk->p_pageData->cp_now_page->StoreData )
  {
    p_wk->p_pageData->cp_now_page->StoreData( p_wk, p_resort_sv );
  }
}
static BOOL Page_ReStoreData( RESONANCE_RESORT_SV *p_resort_sv, const DEBUG_INPUT_WORK *cp_wk )
{
  if( cp_wk->p_pageData->cp_now_page->ReStoreData )
  {
    return cp_wk->p_pageData->cp_now_page->ReStoreData( p_resort_sv, cp_wk );
  }

  return FALSE;
}


