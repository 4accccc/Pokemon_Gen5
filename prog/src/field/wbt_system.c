#include <gflib.h>

#include "wbt.h"

//============================================================================================
//============================================================================================
//------------------------------------------------------------------
/**
 * @brief WBT中に保持する進行データ
 */
//------------------------------------------------------------------
struct _WBT_SYSTEM {
  ///トーナメントの種類
  WBTTYPE type;
  ///バトルルール（シングル、ダブル、トリプル、ローテーション）
  WBTRULE rule;

  ///選択したダウンロードデータ
  u8 select_dl_data;
};


//============================================================================================
//============================================================================================

//============================================================================================
//============================================================================================
//------------------------------------------------------------------
//------------------------------------------------------------------
WBTSYS * WBTSYS_Create( HEAPID heapID )
{
  WBTSYS * wbtsys = GFL_HEAP_AllocMemory( heapID, sizeof(WBTSYS) );
  return wbtsys;
}

//------------------------------------------------------------------
//------------------------------------------------------------------
void WBTSYS_Delete( WBTSYS * wbtsys )
{
  GFL_HEAP_FreeMemory( wbtsys );
}

