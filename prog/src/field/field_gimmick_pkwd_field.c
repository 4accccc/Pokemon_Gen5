//--------------------------------------------------------------
void PKWD_FIELD_End( FIELDMAP_WORK *p_fieldmap )
{
  //汎用ワーク解放
  GMK_TMP_WK_FreeWork( p_fieldmap, PKWD_FIELD_TMP_ASSIGN_ID );
}

