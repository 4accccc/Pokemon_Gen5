//--------------------------------------------------------------
void REZI_GIMMICK_Move( FIELDMAP_WORK *p_fieldmap )
{
  REZI_GIMMICK_TMP *p_wk = GMK_TMP_WK_GetWork( p_fieldmap, GIMMICK_TMP_ASSIGN_ID );

  // EXPOBJアニメメイン
  EXPOBJ_ObjMain( p_wk );
}


